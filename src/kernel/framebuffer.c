void fb_init(void) {
    fb_info.width = 800;
    fb_info.height = 600;
    fb_info.bpp = 32;
    fb_info.format = FB_FORMAT_BGRX8888;
    fb_info.buffer = 0;
    fb_info.pitch = fb_info.width * 4;
    fb_info.size = fb_info.pitch * fb_info.height;
    fb_initialized = 1;
}

int fb_set_mode(uint32_t width, uint32_t height, uint32_t bpp) {
    if (!fb_initialized) fb_init();
    
    fb_info.width = width;
    fb_info.height = height;
    fb_info.bpp = bpp;
    fb_info.format = FB_FORMAT_BGRX8888;
    fb_info.pitch = width * (bpp / 8);
    fb_info.size = fb_info.pitch * height;
    
    return 0;
}

void fb_get_info(struct framebuffer_info* info) {
    if (info) *info = fb_info;
}

void fb_putpixel(int x, int y, uint32_t color) {
    if (x < 0 || x >= (int)fb_info.width || y < 0 || y >= (int)fb_info.height) return;
    if (!fb_info.buffer) return;
    
    uint32_t* p = (uint32_t*)((uint8_t*)fb_info.buffer + y * fb_info.pitch + x * 4);
    *p = color;
}

uint32_t fb_getpixel(int x, int y) {
    if (x < 0 || x >= (int)fb_info.width || y < 0 || y >= (int)fb_info.height) return 0;
    if (!fb_info.buffer) return 0;
    
    uint32_t* p = (uint32_t*)((uint8_t*)fb_info.buffer + y * fb_info.pitch + x * 4);
    return *p;
}

void fb_clear(uint32_t color) {
    if (!fb_info.buffer) return;
    
    uint32_t* p = (uint32_t*)fb_info.buffer;
    uint32_t count = fb_info.size / 4;
    for (uint32_t i = 0; i < count; i++) {
        p[i] = color;
    }
}

void fb_fill_rect(int x, int y, int w, int h, uint32_t color) {
    for (int j = y; j < y + h; j++) {
        for (int i = x; i < x + w; i++) {
            fb_putpixel(i, j, color);
        }
    }
}

void fb_draw_rect(int x, int y, int w, int h, uint32_t color) {
    fb_draw_line(x, y, x + w - 1, y, color);
    fb_draw_line(x, y + h - 1, x + w - 1, y + h - 1, color);
    fb_draw_line(x, y, x, y + h - 1, color);
    fb_draw_line(x + w - 1, y, x + w - 1, y + h - 1, color);
}

void fb_draw_line(int x0, int y0, int x1, int y1, uint32_t color) {
    int dx = x1 - x0;
    int dy = y1 - y0;
    
    if (dx < 0) dx = -dx;
    if (dy < 0) dy = -dy;
    
    int steps = (dx > dy) ? dx : dy;
    if (steps == 0) {
        fb_putpixel(x0, y0, color);
        return;
    }
    
    float xinc = (float)(x1 - x0) / steps;
    float yinc = (float)(y1 - y0) / steps;
    
    float x = (float)x0;
    float y = (float)y0;
    
    for (int i = 0; i <= steps; i++) {
        fb_putpixel((int)x, (int)y, color);
        x += xinc;
        y += yinc;
    }
}

void fb_draw_circle(int cx, int cy, int r, uint32_t color) {
    int x = r;
    int y = 0;
    int err = 0;
    
    while (x >= y) {
        fb_putpixel(cx + x, cy + y, color);
        fb_putpixel(cx + y, cy + x, color);
        fb_putpixel(cx - y, cy + x, color);
        fb_putpixel(cx - x, cy + y, color);
        fb_putpixel(cx - x, cy - y, color);
        fb_putpixel(cx - y, cy - x, color);
        fb_putpixel(cx + y, cy - x, color);
        fb_putpixel(cx + x, cy - y, color);
        
        y++;
        err += 1 + 2 * y;
        if (2 * (err - x) + 1 > 0) {
            x--;
            err += 1 + 2 * (x - y);
        }
    }
}

void fb_draw_filled_circle(int cx, int cy, int r, uint32_t color) {
    for (int yr = -r; yr <= r; yr++) {
        for (int xr = -r; xr <= r; xr++) {
            if (xr*xr + yr*yr <= r*r) {
                fb_putpixel(cx + xr, cy + yr, color);
            }
        }
    }
}

void fb_draw_char(int x, int y, char c, uint32_t fg, uint32_t bg) {
    int idx = (int)c * 8;
    if (idx < 0 || idx >= 2048) return;
    
    for (int row = 0; row < 8; row++) {
        uint8_t line = font_8x8[idx + row];
        for (int col = 0; col < 8; col++) {
            if (line & (0x80 >> col)) {
                fb_putpixel(x + col, y + row, fg);
            } else if (bg) {
                fb_putpixel(x + col, y + row, bg);
            }
        }
    }
}

void fb_draw_string(int x, int y, const char* s, uint32_t fg, uint32_t bg) {
    int px = x;
    while (*s) {
        if (*s == '\n') {
            y += 10;
            px = x;
        } else {
            fb_draw_char(px, y, *s, fg, bg);
            px += 8;
        }
        s++;
    }
}

